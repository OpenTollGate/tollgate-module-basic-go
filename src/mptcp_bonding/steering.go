// NDS-aware guest steering for the MPTCP bond.
//
// # WHY THE SOURCE CIDR IS NOT ENOUGH
//
// TollGate's captive portal authorises a client by setting a packet mark:
//
//	0x00010000 pre-authenticated  -> must stay captive
//	0x00020000 trusted            -> admitted
//	0x00030000 authenticated      -> admitted
//
// (packaging/files/etc/nftables.d/20-nds-enforce.nft). A steering rule keyed
// only on the guest subnet would send PRE-AUTH traffic into the paid bond
// before the portal ever admitted it — a free tunnel that looks healthy. The
// rule in this file therefore matches the NDS mark and runs after NDS's
// priority -150 marking chain.
//
// # WHY A CHAIN, NOT A NEW TABLE
//
// Files under /etc/nftables.d are included inside fw4's `inet fw4` table; a
// nested `table` block is invalid there. This renderer emits a chain fragment
// for that table, plus the fwmark rule/table TPROXY needs.
//
// # WHY THE LOCAL ADDRESSES ARE RUNTIME
//
// The chain must `return` for traffic addressed to the router itself. A
// hardcoded list would miss a DHCP address change and divert SSH into the
// proxy — the exact field failure the MT6000 work records. The apply script
// fills __LOCAL_ADDRS__ from `ip -4 addr show` before loading the file.
package mptcp_bonding

import (
	"fmt"
	"net"
	"strings"
)

const (
	steeringFile = "/etc/nftables.d/50-mptcp-steering.nft"
	// NDS marks from packaging/files/etc/nftables.d/20-nds-enforce.nft.
	ndsTrustedMark       = "0x00020000"
	ndsAuthenticatedMark = "0x00030000"
	// NDS marks packets in mangle PREROUTING at priority -150. This chain
	// must run after that (a higher priority number) and before routing.
	steeringPriority = "-140"
)

// SteeringNFTRules renders the fw4 chain fragment. Callers that write it must
// substitute __LOCAL_ADDRS__ with a comma-separated IPv4 list; an empty list
// is replaced with 127.0.0.1 so the rule remains syntactically valid.
func (c *Config) SteeringNFTRules() string {
	if c == nil || !c.Enabled {
		return ""
	}
	source := strings.TrimSpace(c.SteeringCIDR)
	if source == "" {
		if c.Policy != PolicyAll {
			return ""
		}
		source = "0.0.0.0/0"
	}
	if _, _, err := net.ParseCIDR(source); err != nil {
		return ""
	}

	fwmark := strings.TrimSpace(c.FwMark)
	if fwmark == "" {
		fwmark = "0x1"
	}
	tproxy := c.TproxyPort
	if tproxy == 0 {
		tproxy = 1082
	}

	dontSteer := []string{"__LOCAL_ADDRS__"}
	for _, raw := range c.LocalDontSteerAddrs() {
		raw = strings.TrimSpace(raw)
		if ip := net.ParseIP(raw); ip != nil {
			if ip.To4() != nil {
				dontSteer = append(dontSteer, ip.String())
			}
			continue
		}
		if ip, network, err := net.ParseCIDR(raw); err == nil && ip.To4() != nil {
			dontSteer = append(dontSteer, network.String())
		}
	}
	// Deduplicate while preserving order (placeholder first).
	seen := map[string]bool{}
	uniq := dontSteer[:0]
	for _, a := range dontSteer {
		if !seen[a] {
			seen[a] = true
			uniq = append(uniq, a)
		}
	}

	var b strings.Builder
	b.WriteString("# Generated by tollgate mptcp_bonding. Do not edit: re-rendered.\n")
	b.WriteString("# Chain included inside fw4's inet table; runs after NDS marking (-150).\n")
	b.WriteString("chain mptcp_steer {\n")
	fmt.Fprintf(&b, "    type filter hook prerouting priority %s; policy accept;\n\n", steeringPriority)
	fmt.Fprintf(&b, "    # Never divert traffic addressed to the router itself (SSH, portal, DNS).\n")
	fmt.Fprintf(&b, "    ip daddr { %s } return\n\n", strings.Join(uniq, ", "))
	b.WriteString("    # Only NDS-admitted traffic. Pre-auth (0x10000) and unmarked traffic\n")
	b.WriteString("    # never enter the paid bond.\n")
	for _, mark := range []string{ndsTrustedMark, ndsAuthenticatedMark} {
		fmt.Fprintf(&b, "    ip saddr %s meta l4proto tcp meta mark & 0x00030000 == %s meta mark set %s tproxy ip to :%d counter accept\n",
			source, mark, fwmark, tproxy)
	}
	b.WriteString("}\n")
	return b.String()
}

// SteeringApplyScript writes the chain, installs the fwmark rule/table TPROXY
// needs, and reloads fw4 only when the file content changed. A reload restarts
// nodogsplash, so an idempotent reconcile must not reload every time.
func (c *Config) SteeringApplyScript() string {
	rules := c.SteeringNFTRules()
	if rules == "" {
		return ""
	}
	fwmark := strings.TrimSpace(c.FwMark)
	if fwmark == "" {
		fwmark = "0x1"
	}
	table := c.FwMarkTable
	if table == 0 {
		table = 100
	}

	var b strings.Builder
	b.WriteString("#!/bin/sh\nset -e\n")
	fmt.Fprintf(&b, "FILE=%s\n", steeringFile)
	// BusyBox on OpenWrt has no `paste`; use tr/sed (the missing command made
	// the whole steering script exit 127 on the MT3000).
	b.WriteString(`LOCALS=$(ip -4 addr show 2>/dev/null | awk '/inet /{print $2}' | cut -d/ -f1 | sort -u | tr '\n' ',' | sed 's/,$//')
[ -n "$LOCALS" ] || LOCALS=127.0.0.1
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT
cat > "$TMP" <<'NFTEOF'
`)
	b.WriteString(rules)
	b.WriteString(`NFTEOF
sed -i "s/__LOCAL_ADDRS__/$LOCALS/" "$TMP"
CHANGED=0
if [ -f "$FILE" ] && cmp -s "$TMP" "$FILE"; then
    :
else
    mv "$TMP" "$FILE"
    CHANGED=1
fi
`)
	fmt.Fprintf(&b, "ip rule del fwmark %s/%s lookup %d pref 90 2>/dev/null || true\n", fwmark, fwmark, table)
	fmt.Fprintf(&b, "ip rule add fwmark %s/%s lookup %d pref 90\n", fwmark, fwmark, table)
	fmt.Fprintf(&b, "ip route replace local default dev lo table %d\n", table)
	b.WriteString(`if [ "$CHANGED" = 1 ]; then
    fw4 reload
fi
if ! nft list chain inet fw4 mptcp_steer >/dev/null 2>&1; then
    echo "mptcp_bonding: steering chain missing after fw4 reload" >&2
    exit 1
fi
`)
	return b.String()
}

// SteeringFlushScript removes the chain, its fwmark rule/table, and reloads
// fw4 only when a steering file was actually present.
func (c *Config) SteeringFlushScript() string {
	if c == nil {
		return ""
	}
	// Deliberately does NOT require Enabled: the disable path may carry the
	// steering CIDR it is trying to remove.
	if strings.TrimSpace(c.SteeringCIDR) == "" && c.Policy != PolicyAll {
		return ""
	}
	fwmark := strings.TrimSpace(c.FwMark)
	if fwmark == "" {
		fwmark = "0x1"
	}
	table := c.FwMarkTable
	if table == 0 {
		table = 100
	}
	var b strings.Builder
	b.WriteString("#!/bin/sh\nset -e\n")
	fmt.Fprintf(&b, "FILE=%s\n", steeringFile)
	b.WriteString(`RELOAD=0
if [ -f "$FILE" ]; then
    rm -f "$FILE"
    RELOAD=1
fi
`)
	fmt.Fprintf(&b, "ip rule del fwmark %s/%s lookup %d pref 90 2>/dev/null || true\n", fwmark, fwmark, table)
	fmt.Fprintf(&b, "ip route flush table %d 2>/dev/null || true\n", table)
	b.WriteString(`if [ "$RELOAD" = 1 ]; then
    fw4 reload
fi
`)
	return b.String()
}
