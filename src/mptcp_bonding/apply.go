// The applier: turn a validated Config into an ordered, idempotent shell
// script that puts the kernel into the desired MPTCP state.
//
// This is deliberately a *renderer*, not an executor. It performs no I/O and
// runs no commands, so the exact script can be asserted in a unit test and the
// same bytes can be handed to whatever applies it (a systemd unit, the module's
// existing applier, an Ansible task, or an operator reading it). Keeping it
// pure also means a reconcile loop can diff the rendered script without side
// effects.
//
// The script is safe to run repeatedly. That is the whole point: a reconcile
// runs on every boot and every interface change, and a script that only works
// the first time leaves a field device unconfigured after one reboot.
package mptcp_bonding

import (
	"fmt"
	"strings"
)

// shebang and fail-fast prologue for every rendered script.
const applyPrologue = `#!/bin/sh
# Generated by tollgate mptcp_bonding. Do not edit: re-rendered on reconcile.
set -e
`

// ApplyScript renders the full idempotent script for this bond, or "" when the
// bond is disabled.
//
// Ordering is load-bearing:
//
//  1. Verify MPTCP is available. If the kernel has MPTCP off, everything below
//     fails confusingly ("mptcp: unknown command" from BusyBox ip, or a refused
//     socket), so fail with a clear message instead.
//  2. Set limits, so the ceilings are in place before endpoints exist. Raising
//     the ceiling after registration would leave the first endpoints rejected.
//  3. Register endpoints, each guarded by a delete of the same address so a
//     re-run cannot fail on a duplicate.
//
// The bind password is intentionally never rendered: it belongs in the
// transport's own configuration, and writing it into a generated script would
// put a credential in a file with a predictable path.
func (c *Config) ApplyScript() string {
	if !c.Enabled {
		return ""
	}

	var b strings.Builder
	b.WriteString(applyPrologue)

	// 1. Preconditions, stated so a failure is diagnosable from the log.
	b.WriteString(`
# MPTCP must be present. BusyBox ` + "`ip`" + ` has no ` + "`mptcp`" + ` subcommand, so
# ip-full is required; check both before touching state.
command -v ip >/dev/null 2>&1 || { echo "mptcp_bonding: ip not found" >&2; exit 1; }
if [ "$(cat /proc/sys/net/mptcp/enabled 2>/dev/null || echo 0)" != "1" ]; then
    echo "mptcp_bonding: MPTCP is disabled or unavailable in this kernel" >&2
    exit 1
fi
if ! ip mptcp limits >/dev/null 2>&1; then
    echo "mptcp_bonding: this ip has no mptcp subcommand; install ip-full" >&2
    exit 1
fi
`)

	// 2. Limits first.
	b.WriteString("\n# Ceilings, before any endpoint exists.\n")
	b.WriteString(c.LimitsSetCommand())
	b.WriteString("\n")

	// 3. Endpoints.
	//
	// Two facts learned from the device (OpenWrt 24.10.2, kernel 6.12.94):
	//
	//   a. `ip mptcp endpoint delete <addr>` is INVALID: the id is mandatory
	//      ("delete id ID [ADDRESS]"). Deleting by address silently fails, the
	//      add then hits EEXIST (-17), and under `set -e` the apply exits 2.
	//   b. `ip mptcp endpoint show` prints "ADDRESS id N dev IFACE", so the id
	//      is field 3 -- field 4 is the literal string "dev".
	//
	// So resolve the id from the live list. Crucially, if the address is already
	// registered with the right device we DO NOTHING: delete-then-add is not
	// idempotent in effect even when it succeeds, because it removes the
	// endpoint and allocates a new id, which would interrupt an in-flight
	// subflow on every reconcile. Only a missing or wrong-device endpoint is
	// corrected.
	b.WriteString("\n# Uplink endpoints. Already-correct endpoints are left ALONE: removing\n")
	b.WriteString("# and re-adding would churn the id and interrupt a live subflow.\n")
	for _, cmd := range c.EndpointPlan() {
		addr, dev, ok := endpointParts(cmd)
		if !ok {
			// Should not happen: EndpointPlan only emits well-formed commands.
			continue
		}
		fmt.Fprintf(&b, "cur_id=$(ip mptcp endpoint show | awk -v a=\"%s\" '$1==a && $2==\"id\" {print $3}'); \\\n", addr)
		fmt.Fprintf(&b, "  cur_dev=$(ip mptcp endpoint show | awk -v a=\"%s\" '$1==a {for(i=1;i<=NF;i++) if($i==\"dev\") print $(i+1)}'); \\\n", addr)
		fmt.Fprintf(&b, "  if [ -n \"$cur_id\" ] && [ \"$cur_dev\" = \"%s\" ]; then :; else \\\n", dev)
		fmt.Fprintf(&b, "    [ -n \"$cur_id\" ] && ip mptcp endpoint delete id \"$cur_id\" 2>/dev/null || true; \\\n")
		fmt.Fprintf(&b, "    %s || true; \\\n", cmd)
		fmt.Fprintf(&b, "  fi\n")
	}

	return b.String()
}

// endpointParts extracts the address and device from a rendered
// `ip mptcp endpoint add <addr> dev <dev> signal subflow` command.
func endpointParts(cmd string) (addr, dev string, ok bool) {
	fields := strings.Fields(cmd)
	// ip mptcp endpoint add <addr> dev <dev> signal subflow
	if len(fields) < 7 || fields[3] != "add" || fields[5] != "dev" {
		return "", "", false
	}
	return fields[4], fields[6], true
}
