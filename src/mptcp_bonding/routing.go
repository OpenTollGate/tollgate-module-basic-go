// Per-uplink policy routing for a non-tunnel MPTCP bond.
//
// # WHY THIS EXISTS
//
// Registering two endpoints is not enough to make two subflows leave through
// two uplinks. The kernel picks a route for each new subflow, and with two
// default routes the second subflow can follow the *primary* uplink while
// carrying the second uplink's source address. The far end then sees a SYN
// from an address that does not belong to the path it arrived on: the JOIN is
// silently dropped and the bond stays single-path while every counter looks
// plausible. The MT6000 lab work calls this out as the mandatory second half
// of the bond ("policy routing is MANDATORY for the 2nd subflow").
//
// Each uplink therefore gets:
//
//   - a dedicated routing table with the connected subnet, the uplink's own
//     /32, and a default route via that uplink's gateway;
//   - an `ip rule from <uplink-address> lookup <table>` so a subflow sourced
//     from that address ignores the primary default route.
//
// The gateway is discovered at apply time because it is DHCP state, not
// configuration. A missing gateway is loud: it means the uplink cannot be
// pinned and the bond would otherwise look healthy while using one path.
package mptcp_bonding

import (
	"fmt"
	"net"
	"strings"
)

// PolicyRoutingScript renders a complete, standalone script for the bond's
// per-uplink routing. ApplyScript embeds the same fragment; this form is for
// operators and tests that want to inspect or run it on its own.
func (c *Config) PolicyRoutingScript() string {
	if c == nil || !c.Enabled {
		return ""
	}
	frag := c.policyRoutingFragment()
	if frag == "" {
		return ""
	}
	return "#!/bin/sh\n# Generated by tollgate mptcp_bonding. Pins each subflow to its uplink.\nset -e\n" + frag
}

// policyRoutingFragment is the part ApplyScript embeds. Tunnels have their own
// pinning mechanism (fwmark + TunnelRoutingScript), so this fragment is only
// rendered for the non-tunnel shape; emitting both would install two competing
// sets of rules for the same address.
func (c *Config) policyRoutingFragment() string {
	if c == nil || !c.Enabled || len(c.Tunnels) > 0 {
		return ""
	}

	base := c.FwMarkTable
	if base == 0 {
		base = 100
	}

	var b strings.Builder
	b.WriteString("\n# Per-uplink policy routing. Without this the second subflow follows\n")
	b.WriteString("# the primary default route with a foreign source and is dropped.\n")
	b.WriteString("ROUTE_FAILED=0\n")

	rendered := 0
	for i, u := range c.Uplinks {
		addr := strings.TrimSpace(u.Address)
		iface := strings.TrimSpace(u.Interface)
		if addr == "" || iface == "" {
			continue
		}
		if ip, _, err := net.ParseCIDR(addr); err == nil {
			addr = ip.String()
		}
		ip := net.ParseIP(addr)
		if ip == nil {
			continue
		}
		// This fragment renders IPv4 rules (`/32`, `ip route`). IPv6 needs
		// `ip -6 rule`/`ip -6 route` and a /128; leave it to a later change
		// rather than emitting commands that silently do the wrong thing.
		if ip.To4() == nil {
			continue
		}

		table := base + 1 + i
		pref := 100 + i
		fmt.Fprintf(&b, "TABLE=%d; IFACE=%s; ADDR=%s; PREF=%d\n", table, iface, addr, pref)
		b.WriteString(`GW=$(ip route show dev "$IFACE" 2>/dev/null | awk '/^default via /{print $3; exit}')
if [ -z "$GW" ]; then
    GW=$(ip route show default 2>/dev/null | awk -v d="$IFACE" '$0 ~ ("dev " d "( |$)") {print $3; exit}')
fi
CONNECTED=$(ip route show dev "$IFACE" scope link 2>/dev/null | awk '$1 ~ /\// {print $1; exit}')
if [ -n "$CONNECTED" ]; then
    ip route replace "$CONNECTED" dev "$IFACE" table "$TABLE" 2>/dev/null || true
fi
ip route replace "$ADDR/32" dev "$IFACE" table "$TABLE" 2>/dev/null || true
if [ -n "$GW" ]; then
    ip route replace default via "$GW" dev "$IFACE" table "$TABLE" 2>/dev/null || {
        echo "mptcp_bonding: default route failed for $IFACE table $TABLE" >&2
        ROUTE_FAILED=1
    }
else
    echo "mptcp_bonding: no gateway found for $IFACE; cannot pin its subflow" >&2
    ROUTE_FAILED=1
fi
ip rule del from "$ADDR"/32 lookup "$TABLE" 2>/dev/null || true
ip rule add from "$ADDR"/32 lookup "$TABLE" pref "$PREF" 2>/dev/null || {
    echo "mptcp_bonding: policy rule failed for $ADDR table $TABLE" >&2
    ROUTE_FAILED=1
}
`)
		rendered++
	}

	if rendered == 0 {
		return ""
	}
	b.WriteString("if [ \"$ROUTE_FAILED\" = 1 ]; then\n")
	b.WriteString("    echo \"mptcp_bonding: one or more uplink policy routes failed\" >&2\n")
	b.WriteString("    exit 1\n")
	b.WriteString("fi\n")
	return b.String()
}

// PolicyRoutingFlushScript removes the rules and tables a previous enabled
// boot installed. Without it, disabling the bond leaves `ip rule` entries and
// dedicated tables behind, and a later bond with the same addresses inherits
// stale state. It is a fragment, not a full script: the caller runs it after
// FlushScript's endpoint flush. Only the configured uplinks are touched; a
// section that was deleted entirely leaves no addresses to target, which is
// why the caller also has to reconcile the live ruleset when it can.
func (c *Config) PolicyRoutingFlushScript() string {
	if c == nil || len(c.Tunnels) > 0 {
		return ""
	}
	base := c.FwMarkTable
	if base == 0 {
		base = 100
	}

	var b strings.Builder
	rendered := 0
	for i, u := range c.Uplinks {
		addr := strings.TrimSpace(u.Address)
		if addr == "" {
			continue
		}
		if ip, _, err := net.ParseCIDR(addr); err == nil {
			addr = ip.String()
		}
		ip := net.ParseIP(addr)
		if ip == nil || ip.To4() == nil {
			continue
		}
		if rendered == 0 {
			b.WriteString("\n# Remove per-uplink policy routing left by a previous enabled boot.\n")
		}
		table := base + 1 + i
		fmt.Fprintf(&b, "ip rule del from %s/32 lookup %d 2>/dev/null || true\n", addr, table)
		fmt.Fprintf(&b, "ip route flush table %d 2>/dev/null || true\n", table)
		rendered++
	}
	return b.String()
}
