func TestRenderDisabled(t *testing.T) {
	got, err := RenderFW4(Config{GuestInterface: "invalid;"}, "")
	if got != "" || err != nil {
		t.Fatalf("disabled = %q, %v", got, err)
	}
}

func TestRenderRejectsInvalid(t *testing.T) {
	for _, change := range []func(*Config){
		func(c *Config) { c.MTU = 1241 },
		func(c *Config) { c.TunnelInterface = "bad\";" },
		func(c *Config) { c.Selection = "all" },
	} {
		c := validConfig()
		change(&c)
		got, err := RenderFW4(c, c.GuestInterface)
		if err == nil || got != "" {
			t.Fatalf("invalid config rendered: %q, %v", got, err)
		}
	}
	for _, portal := range []string{"", "other-guest", "bad\";"} {
		got, err := RenderFW4(validConfig(), portal)
		if err == nil || got != "" {
			t.Fatalf("mismatched portal define rendered: %q, %v", got, err)
		}
	}
}

func TestRenderGuardContract(t *testing.T) {
	for _, mtu := range []int{576, 1200, 1240} {
		c := validConfig()
		c.MTU = mtu
		c.GuestInterface = "renamed-guest"
		c.TunnelInterface = "renamed-exit"
		before := c
		got, err := RenderFW4(c, c.GuestInterface)
		if err != nil {
			t.Fatal(err)
		}
		if c != before {
			t.Fatal("render mutated config")
		}
		_, inner := Derive(c.LocalPublicKey)
		want := fmt.Sprintf(`# FIPS exit guard: include inside table inet fw4 after 00-tollgate-defs.nft.
define tg_fexit_tunnel_if = "renamed-exit"

chain tg_fexit_forward {
    type filter hook forward priority -2; policy accept;
    meta nfproto ipv6 iifname $tg_portal_if counter drop
    iifname $tg_portal_if oifname != $tg_fexit_tunnel_if counter drop
    meta nfproto ipv4 iifname $tg_portal_if oifname $tg_fexit_tunnel_if tcp flags & syn == syn tcp option maxseg size > %[1]d tcp option maxseg size set %[1]d
    meta nfproto ipv4 iifname $tg_fexit_tunnel_if oifname $tg_portal_if ct state established,related tcp flags & syn == syn tcp option maxseg size > %[1]d tcp option maxseg size set %[1]d
    meta nfproto ipv4 iifname $tg_fexit_tunnel_if oifname $tg_portal_if ct state established,related return
    iifname $tg_fexit_tunnel_if oifname $tg_portal_if counter drop
}

chain tg_fexit_srcnat {
    type nat hook postrouting priority 99; policy accept;
    meta nfproto ipv4 iifname $tg_portal_if oifname $tg_fexit_tunnel_if snat ip to %[2]s
}
`, mtu-40, inner)
		if got != want {
			t.Fatalf("guard contract mismatch (-want +got):\nWANT:\n%s\nGOT:\n%s", want, got)
		}
		for _, forbidden := range []string{" counter accept", "hook input", "hook output", "meta mark", "masquerade", "snat ip6", "br-", "nft add", "nft insert"} {
			if strings.Contains(got, forbidden) {
				t.Errorf("forbidden %q", forbidden)
			}
		}
	}
}

// This check never touches the host namespace. A skipped check is NOT kernel
// validation. Exact generated bytes are wrapped only with the caller-owned define.
func TestRenderNFTCheckIsolated(t *testing.T) {
	nft, err := exec.LookPath("nft")
	if err != nil {
		t.Skip("NOT RUN: nft unavailable")
	}
	unshare, err := exec.LookPath("unshare")
	if err != nil {
		t.Skip("NOT RUN: unshare unavailable")
	}
	if out, err := exec.Command(unshare, "-Urn", "--", "true").CombinedOutput(); err != nil {
		t.Skipf("NOT RUN: isolated user/network namespace unavailable: %v: %s", err, out)
	}
	c := validConfig()
	fragment, err := RenderFW4(c, c.GuestInterface)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "guard.nft")
	input := fmt.Sprintf("table inet fw4 {\ndefine tg_portal_if = %q\n%s}\n", c.GuestInterface, fragment)
	if err := os.WriteFile(path, []byte(input), 0600); err != nil {
		t.Fatal(err)
	}
	if out, err := exec.Command(unshare, "-Urn", "--", nft, "-c", "-f", path).CombinedOutput(); err != nil {
		t.Fatalf("generated fragment rejected: %v: %s", err, out)
	}
}
